export interface EncryptedPayload {
  /** Base64-encoded ciphertext */
  readonly ciphertext: string;
  /** Base64-encoded initialization vector */
  readonly iv: string;
  /** Base64-encoded authentication tag */
  readonly tag: string;
}

// ─── Log Models ──────────────────────────────────────────────────────────────

/**
 * @description A single log entry recorded by the LogService.
 */
export interface LogEntry {
  /** ISO 8601 timestamp */
  readonly timestamp: string;
  /** Module that generated the log */
  readonly module: string;
  /** Log level */
  readonly level: 'error' | 'warning' | 'info' | 'security';
  /** Log message */
  readonly message: string;
  /** Stack trace if applicable */
  readonly stackTrace?: string;
  /** Additional context */
  readonly context?: Record<string, unknown>;
}

/**
 * @description Filter options for querying logs.
 */
export interface LogFilter {
  /** Filter by module name */
  readonly module?: string;
  /** Filter by log level */
  readonly level?: LogEntry['level'];
  /** Filter logs after this timestamp */
  readonly since?: string;
  /** Maximum number of entries to return */
  readonly limit?: number;
}

// ─── Session State ───────────────────────────────────────────────────────────

/**
 * @description Complete session state persisted in localStorage.
 * Serialized as JSON with encrypted API keys.
 */
export interface SessionState {
  /** Schema version for future migrations */
  readonly version: number;
  /** Unique session identifier */
  readonly sessionId: string;
  /** Timestamp of last modification (Unix ms) */
  readonly lastModified: number;
  /** Current step in the onboarding flow */
  readonly currentStep: FlowStep;
  /** Loaded file data, null if no file loaded */
  readonly fileData: FileLoadResult | null;
  /** Structure detection result */
  readonly detectionResult: DetectionResult | null;
  /** PRISM audit result */
  readonly prismResult: PRISMResult | null;
  /** Selected and custom visualizations */
  readonly visualizations: Visualization[];
  /** Selected KPIs */
  readonly selectedKPIs: KPISuggestion[];
  /** Strategic objectives defined by user */
  readonly objectives: StrategicObjective[];
  /** KPI-Objective links */
  readonly links: KPILink[];
  /** IA configuration and history */
  readonly iaConfig: {
    readonly activeProviderId: string | null;
    readonly providers: IAProviderConfig[];
    readonly queryHistory: IAResponse[];
  };
  /** User customizations for document regeneration */
  readonly userCustomizations: UserCustomizations;
  /** UI preferences */
  readonly uiPreferences: {
    readonly theme: Theme;
    readonly locale: string;
  };
}
