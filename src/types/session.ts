import type {
  DataType,
  BSCPerspective,
  PRISMDimension,
  ChartType,
  AggregationType,
  FlowStep,
  Theme
} from './common';

// ─── File Loading Models ─────────────────────────────────────────────────────

/**
 * @description Result of a successful file load operation.
 * Contains metadata and parsed data from the uploaded file.
 */
export interface FileLoadResult {
  /** Original file name */
  readonly fileName: string;
  /** File size in bytes */
  readonly fileSize: number;
  /** Number of sheets (1 for CSV) */
  readonly sheetCount: number;
  /** Total rows processed (max 100,000) */
  readonly totalRows: number;
  /** Whether the file was truncated to 100K rows */
  readonly wasTruncated: boolean;
  /** Parsed data per sheet */
  readonly sheets: SheetData[];
}

/**
 * @description Parsed data for a single sheet within a file.
 */
export interface SheetData {
  /** Sheet name */
  readonly name: string;
  /** Column header names */
  readonly headers: string[];
  /** Data rows (max 100,000 total across all sheets) */
  readonly rows: unknown[][];
  /** Original row count before truncation */
  readonly originalRowCount: number;
}

// ─── Detection Models ────────────────────────────────────────────────────────

/**
 * @description Metadata about a single column detected in a sheet.
 */
export interface ColumnInfo {
  /** Column name from header */
  readonly name: string;
  /** Type detected automatically via sampling */
  readonly detectedType: DataType;
  /** Type assigned (may be modified by user) */
  assignedType: DataType;
  /** Percentage of empty values (0-100) */
  readonly emptyPercentage: number;
  /** Count of non-empty records */
  readonly recordCount: number;
  /** True if emptyPercentage > 30 */
  readonly hasWarning: boolean;
}

/**
 * @description Structure analysis result for a single sheet.
 */
export interface SheetStructure {
  /** Name of the sheet */
  readonly sheetName: string;
  /** Column information array */
  readonly columns: ColumnInfo[];
  /** Total records in this sheet */
  readonly totalRecords: number;
}

/**
 * @description Complete result of the structure detection analysis.
 */
export interface DetectionResult {
  /** Structure per analyzed sheet */
  readonly sheets: SheetStructure[];
  /** Number of sheets analyzed (max 50) */
  readonly analyzedSheets: number;
  /** Number of sheets skipped */
  readonly skippedSheets: number;
  /** Whether at least one sheet has valid tabular structure */
  readonly hasValidStructure: boolean;
}

// ─── PRISM Models ────────────────────────────────────────────────────────────

/**
 * @description Detail about a specific problem found during PRISM evaluation.
 */
export interface ProblemDetail {
  /** Location identifier (column name or row index) */
  readonly location: string;
  /** Human-readable description of the problem */
  readonly description: string;
  /** Impact on the dimension score (0-100) */
  readonly impact: number;
}

/**
 * @description Score and observations for a single PRISM dimension.
 */
export interface DimensionScore {
  /** The dimension being evaluated */
  readonly dimension: PRISMDimension;
  /** Quality score (integer 0-100) */
  readonly score: number;
  /** Textual observations about this dimension */
  readonly observations: string[];
  /** Specific problems found (max 10 per dimension) */
  readonly problems: ProblemDetail[];
}

/**
 * @description Complete result of PRISM quality evaluation.
 */
export interface PRISMResult {
  /** Scores for all 5 dimensions */
  readonly dimensions: DimensionScore[];
  /** True if all dimensions score 0 (blocks visualization) */
  readonly isBlockingQuality: boolean;
  /** True if Integrity dimension < 30 */
  readonly hasLowIntegrity: boolean;
  /** True if any dimension < 60 */
  readonly hasWarningDimensions: boolean;
}

// ─── Visualization Models ────────────────────────────────────────────────────

/**
 * @description A chart suggestion generated by the visualization catalog.
 */
export interface ChartSuggestion {
  /** Unique identifier */
  readonly id: string;
  /** Type of chart suggested */
  readonly type: ChartType;
  /** Suggested title */
  readonly title: string;
  /** Column names involved in this chart */
  readonly columns: string[];
  /** Rationale for suggesting this chart type */
  readonly rationale: string;
}

/**
 * @description A KPI suggestion generated from data analysis.
 */
export interface KPISuggestion {
  /** Unique identifier */
  readonly id: string;
  /** KPI display name */
  readonly name: string;
  /** Aggregation operation used */
  readonly aggregation: AggregationType;
  /** Primary column for the KPI */
  readonly column: string;
  /** Descriptive formula */
  readonly formula: string;
  /** Computed value from current data, null if not computable */
  readonly computedValue: number | null;
}

/**
 * @description Configuration for rendering a visualization.
 */
export interface VisualizationConfig {
  /** Color scheme or specific colors */
  readonly colors: string[];
  /** Axis and data labels */
  readonly labels: Record<string, string>;
  /** Data range constraints */
  readonly dataRange: {
    readonly min?: number;
    readonly max?: number;
    readonly startDate?: string;
    readonly endDate?: string;
  };
}

/**
 * @description A configured visualization (suggested or custom).
 */
export interface Visualization {
  /** Unique identifier */
  readonly id: string;
  /** Type of chart */
  readonly type: ChartType;
  /** Display title (max 100 chars) */
  readonly title: string;
  /** Rendering configuration */
  readonly config: VisualizationConfig;
  /** Column names assigned to this visualization */
  readonly dataColumns: string[];
  /** Whether this was manually created by the user */
  readonly isCustom: boolean;
}

